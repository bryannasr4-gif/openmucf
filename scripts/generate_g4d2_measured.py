"""Generate and check the measured oxide capture vectors and their decisions.

``generate`` writes, under ``data/g4/d2/measured/``, one Layer-1 table and its Layer-2 file per oxide row of
Stanislaus et al. (1987) Table 1, ``evaluation.json`` (the delivered vectors, the stock selector's values and
every decision) and ``inventory.json`` (each file's size and SHA-256), from the committed source rows
``data/g4/reference/d2/measurements.csv`` and ``printed_rows.csv``, the committed ``inputs.json`` and the shared
convention record ``data/g4/d1/bound_decay_response_v1.json``, read in place. It renders
``docs/measured-oxide-capture.md`` from the evaluation. ``check`` recomputes everything and refuses a
committed file that is not byte for byte its recomputation, a missing file and an extra one. The work is done
by :mod:`openmucf.g4.d2_measured`; nothing here reads a file that is not public.
"""

from __future__ import annotations

import argparse
import json
from decimal import ROUND_DOWN, Decimal
from pathlib import Path

from openmucf.g4 import d2_measured as measured

ROOT = Path(__file__).resolve().parents[1]
DIRECTORY = Path("data/g4/d2/measured")
DOCUMENT_RELPATH = Path("docs/measured-oxide-capture.md")
MEASUREMENTS = Path("data/g4/reference/d2/measurements.csv")
PRINTED = Path("data/g4/reference/d2/printed_rows.csv")


def recompute(root: Path) -> dict[str, bytes]:
    inputs_raw = (root / DIRECTORY / measured.INPUTS_NAME).read_bytes()
    shared_path = measured.load_inputs(inputs_raw).shared_path
    return measured.generate(
        (root / MEASUREMENTS).read_bytes(),
        (root / PRINTED).read_bytes(),
        inputs_raw,
        (root / shared_path).read_bytes(),
    )


def render_document(evaluation: dict) -> bytes:
    rows = evaluation["rows"]
    lines = []
    for r in rows:
        missing = "; ".join(r["improvement"]["missing"])
        p, s = (Decimal(x).quantize(Decimal("0.000001")) for x in (r["delivery"]["p_metal"], r["stock_p_metal"]))
        u = Decimal(r["precision"]["U_at_least"]).quantize(Decimal("0.000001"), rounding=ROUND_DOWN)
        lines.append(
            f"| {r['formula']} | {r['A']} | {r['u']} | {p} | {s} | {u} | {r['precision']['verdict']} | "
            f"{r['improvement']['verdict']} | {missing} |"
        )
    table = "\n".join(lines)
    (sens,) = [a for a in evaluation["attempts"] if a["role"] == measured.ROLE_SENSITIVITY]
    margins = ", ".join(f"{f} {v}" for f, v in sens["conditional_min_margin_tv"].items())
    quals = " ".join(f"{f}: {v}." for f, v in sens["qualifications"].items())
    minimum = evaluation["minimum_U_at_least"]
    text = f"""# Measured oxide capture vectors

This page is generated by `scripts/generate_g4d2_measured.py` from `data/g4/d2/measured/evaluation.json`;
`check` holds both to the committed source rows.

## What is delivered

For each oxide `M_mO_n` of Table 1 of Stanislaus et al., Nucl. Phys. A 475 (1987) 630, the source reports the
per-atom atomic capture ratio `A` of the metal to oxygen. The table `data/g4/d2/measured/<profile>.g4dat`
carries, for the nominal hydrogen-free solid of that formula, the probability that a stopped negative muon ends
on each element: `p_M = m A / (n + m A)` and `p_O = 1 - p_M`, the reported value as reported. The vectors are
read only by the opt-in material selector in `cpp/material_selector/`, and only for a material bound to one of
them explicitly; without a binding Geant4's stock selector runs unchanged. The stock selector's value for the
same nominal material is `m Z / (m Z + 0.56 * 8 n)`.

## Precision

Under the registered Cartesian uncertainty construction, the assumed 2% statistical standard scale at k=2
together with the published carbon sensitivity excludes a TV<=0.01 precision certificate for every oxide in
this table. The result does not establish that every central estimate is wrong by more than 0.01. The source
states the carbon origin of its quoted errors and the size of its statistical errors in section 5, p. 636. The
smallest of the per-row lower bounds on the largest total-variation error, `U_at_least` below, is
{minimum['U_at_least']} ({minimum['formula']}).

## Improvement over the stock selector

Improvement over the stock selector is not established for any row. The response of the source's
decay-electron detection to the electron energy, which enters the source's correction of each ratio, is not
validated, and for the {sum(r['hygroscopic'] for r in rows)} rows the source flags as hygroscopic no bound on
water uptake is supported. The other components of the registered region -- the time origin, the run-to-run
difference and the response of the fitted amplitudes to the fixed lifetimes -- are evaluated from inputs this
repository does not redistribute, and are named here rather than distributed.

A separately labelled conditional sensitivity, `{sens['id']}`, is not a decision: {sens['statement']}
({margins}). {quals} It was {sens['disclosure']}.

These are development evaluations of exposed measurements, not independent validation.

## The rows

| oxide | A | u | p_M | stock p_M | U_at_least (rounded down) | precision | improvement | not supported |
|---|---|---|---|---|---|---|---|---|
{table}
"""
    return text.encode("utf-8")


def generate(root: Path) -> None:
    files = recompute(root)
    directory = root / DIRECTORY
    for name, data in files.items():
        (directory / name).write_bytes(data)
    evaluation = json.loads(files[measured.EVALUATION_NAME])
    (root / DOCUMENT_RELPATH).write_bytes(render_document(evaluation))
    counts = evaluation["counts"]
    print(f"measured out={DIRECTORY.as_posix()} files={len(files)} rows={counts['rows']} "
          f"meets_excluded={counts['precision_meets_excluded']} "
          f"improvement_established={counts['improvement_established']} "
          f"minimum_U_at_least={evaluation['minimum_U_at_least']}")


def check(root: Path) -> None:
    files = recompute(root)
    directory = root / DIRECTORY
    committed = {p.name: p.read_bytes() for p in directory.iterdir() if p.is_file()}
    try:
        measured.check_committed(committed, files)
    except measured.MeasuredError as exc:
        raise SystemExit(f"measured check FAILED: {exc}") from exc
    evaluation = json.loads(files[measured.EVALUATION_NAME])
    if (root / DOCUMENT_RELPATH).read_bytes() != render_document(evaluation):
        raise SystemExit(f"measured check FAILED: {DOCUMENT_RELPATH.as_posix()} is not its rendering")
    print(f"measured check ok: {len(committed)} files")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("command", choices=("generate", "check"))
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    if args.command == "generate":
        generate(args.root)
    else:
        check(args.root)


if __name__ == "__main__":
    main()
