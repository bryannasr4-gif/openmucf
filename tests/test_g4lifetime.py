def _raw_text() -> str:
    """A raw harvest rebuilt from the oracle: the lines the driver prints, every A of the sweep included."""
    data = oracle()
    lines = [f"K {name} {data.constants[name].hex()}" for name in ("mu_mass", "alpha", "microsecond")]
    lines += [f"H {z} {data.helper[z].hex()}" for z in lifetime.HELPER_Z]
    lines += [f"B {z} {a} {mass.hex()} {rate.hex()}" for (z, a), (mass, rate) in data.light.items()]
    lines += [f"B {z} {a} {float(a).hex()} {data.heavy[z].hex()}" for z, a in lifetime.heavy_keys()]
    return "\n".join(lines) + "\n"


def _next(value: float) -> str:
    return math.nextafter(value, math.inf).hex()


def _without(text: str, prefix: str) -> str:
    assert sum(line.startswith(prefix) for line in text.split("\n")) == 1, prefix
    return "\n".join(line for line in text.split("\n") if not line.startswith(prefix))


_HELPER_Z = lifetime.HELPER_Z[-1]
_LIGHT_Z, _LIGHT_A = lifetime.light_keys()[-1]


@pytest.mark.parametrize(
    ("mutate", "refusal"),
    [
        (lambda t: t + "a line the driver does not write\n", "not a harvest line"),
        (lambda t: t + f"K mu_mass {_next(oracle().constants['mu_mass'])}\n", "constant mu_mass repeated"),
        (lambda t: t + f"H {_HELPER_Z} {_next(oracle().helper[_HELPER_Z])}\n",
         f"helper Z={_HELPER_Z} repeated"),
        (lambda t: t + f"B {_LIGHT_Z} {_LIGHT_A} {oracle().light[(_LIGHT_Z, _LIGHT_A)][0].hex()} "
                       f"{_next(oracle().light[(_LIGHT_Z, _LIGHT_A)][1])}\n",
         re.escape(f"bound-decay key {(_LIGHT_Z, _LIGHT_A)} repeated")),
        (lambda t: t.replace("K alpha", "K beta", 1), "the constants are"),
        (lambda t: _without(t, f"H {_HELPER_Z} "), "the helper's rates do not cover its Z range"),
        (lambda t: "\n".join(line for line in t.split("\n") if not line.startswith("B 120 300 ")),
         "the bound-decay rates do not cover the sweep"),
    ],
    ids=["foreign", "repeated-constant", "repeated-helper", "repeated-bound", "constant", "missing-helper",
         "missing"],
)
def test_drill_the_raw_parser_refuses_what_the_driver_does_not_print(mutate, refusal):
    lifetime.parse_raw(_raw_text())
    with pytest.raises(lifetime.LifetimeError, match=refusal):
        lifetime.parse_raw(mutate(_raw_text()))


def _raw_tree(root: Path, outputs: tuple[str, str], digest: str, stderr: bytes = b"") -> Path:
    raw = root / "raw"
    for (build, revision), output in zip(lifetime.BUILDS, outputs, strict=True):
        folder = raw / build
        folder.mkdir(parents=True)
        (folder / "decay.txt").write_bytes(output.encode("ascii"))
        (folder / "sha256.txt").write_text(digest + "\n", encoding="ascii")
        version = revision.removeprefix("v").removesuffix(".beta")
        (folder / "version.txt").write_text(version + "\n", encoding="ascii")
        (folder / "gcc.txt").write_text("g++\n", encoding="ascii")
        (folder / "stderr.txt").write_bytes(stderr)
    return raw


def test_drill_the_harvest_refuses_differing_builds_a_foreign_driver_stderr_and_a_mass_dependence(tmp_path):
    """The conversion writes the oracle only when every build compiled the committed driver, wrote nothing to
    stderr and printed the same bytes, and the bound-decay rate does not move with A from the threshold on;
    the oracle it writes holds the committed values."""
    harness = hashlib.sha256((REPO / lifetime.HARNESS_RELPATH).read_bytes()).hexdigest()
    text = _raw_text()
    written = lifetime.harvest(_raw_tree(tmp_path / "ok", (text, text), harness), REPO)
    path = tmp_path / "oracle"
    path.write_bytes(written)
    rebuilt, committed = lifetime.load_oracle(path), oracle()
    assert (rebuilt.constants, rebuilt.helper, rebuilt.light, rebuilt.heavy) == (
        committed.constants, committed.helper, committed.light, committed.heavy)
    assert rebuilt.header["heavy_sha256"] == committed.header["heavy_sha256"]
    first = f"B {lifetime.BOUND_THRESHOLD_Z} {lifetime.BOUND_THRESHOLD_Z + 1} "
    line = next(line for line in text.split("\n") if line.startswith(first))
    moved = text.replace(line, line[:-1] + ("1" if line[-1] != "1" else "2"))
    rate = f"H {_HELPER_Z} {committed.helper[_HELPER_Z].hex()}\n"
    differ = text.replace(rate, f"H {_HELPER_Z} {_next(committed.helper[_HELPER_Z])}\n")
    assert text.count(rate) == 1 and differ != text
    lifetime.parse_raw(differ)
    compiler = _raw_tree(tmp_path / "compiler", (text, text), harness)
    assert committed.header["compiler"] != "g++"
    (compiler / lifetime.BUILDS[-1][0] / "gcc.txt").write_text(
        committed.header["compiler"] + "\n", encoding="ascii")
    for name, raw, refusal in (
        ("differ", _raw_tree(tmp_path / "differ", (text, differ), harness),
         "the builds printed different rates"),
        ("driver", _raw_tree(tmp_path / "driver", (text, text), "0" * 64), "the compiled driver is not"),
        ("stderr", _raw_tree(tmp_path / "stderr", (text, text), harness, b"warning\n"),
         "the driver wrote to stderr"),
        ("mass", _raw_tree(tmp_path / "mass", (moved, moved), harness), "depends on the mass number"),
        ("compiler", compiler, "the builds used different compilers"),
    ):
        with pytest.raises(lifetime.LifetimeError, match=refusal):
            lifetime.harvest(raw, REPO)
        assert name


