BOUND_SIGNATURE = "G4double G4MuonMinusBoundDecay::GetMuonDecayRate(G4int Z, G4int A"
HELPER_SIGNATURE = "G4double G4MuonicAtomHelper::GetMuonDecayRate(G4int Z)"
#: The two decay functions as both vendored revisions write them, comments removed and whitespace dropped:
#: the expressions the ports transcribe, with the literals the ports carry.
BOUND_BODY = (
    "G4doubleG4MuonMinusBoundDecay::GetMuonDecayRate(G4intZ,G4intA,G4doublemuMass,G4doublenuclMass)"
    "{structdecRate{G4intZ;G4intA;G4doubledRate;G4doubledRErr;};staticconstdecRatedecRates[]="
    "{{0,0,0.45517005,0.00000046}};G4doublelambda=-1.;if(Z==0&&A==0){lambda=decRates[0].dRate/microsecond;}"
    "if(lambda<0.){constG4doublefreeMuonDecayRate=0.45517005/microsecond;lambda=1.0;"
    "G4doublex=Z*fine_structure_const;if(Z<14){lambda-=x*x*(0.5+0.06*muMass/nuclMass);}"
    "else{lambda-=x*x*(0.868699-x*0.708985);}lambda*=freeMuonDecayRate;}returnlambda;}"
)
HELPER_BODY = (
    "G4doubleG4MuonicAtomHelper::GetMuonDecayRate(G4intZ){structdecRate{G4intZ;G4doubledRate;"
    "G4doubledRErr;};constexprdecRatedecRates[]={{1,0.4558514,0.0000151}};G4doublelambda=-1.;"
    "if(Z==1){lambda=decRates[0].dRate/microsecond;}if(lambda<0.){constexprG4doublefreeMuonDecayRate="
    "0.45517005/microsecond;lambda=1.0;G4doublex=GetMuonZeff(Z)*fine_structure_const;lambda-=2.5*x*x;"
    "lambda*=freeMuonDecayRate;}returnlambda;}"
)


def oracle() -> lifetime.Oracle:
    return lifetime.load_oracle(REPO / lifetime.ORACLE_RELPATH)


def helper() -> d1.D1Extraction:
    return d1.load_helper(REPO / d1.HELPER_RELPATH)


def comparison() -> list[dict[str, str]]:
    return lifetime.read_comparison(REPO / lifetime.COMPARISON_RELPATH)


def function_body(text: str, signature: str) -> str:
    """The function that starts at ``signature``, comments removed and every whitespace character dropped."""
    text = re.sub(r"//[^\n]*", "", text)
    start = text.index(signature)
    depth, opening = 0, text.index("{", start)
    end = opening
    for end in range(opening, len(text)):
        depth += {"{": 1, "}": -1}.get(text[end], 0)
        if depth == 0:
            break
    return "".join(text[start:end + 1].split())


