def _row_pattern(line: str, numeric: re.Pattern[str]) -> tuple[str, tuple[int, ...]]:
    """A pattern matching ``line`` whitespace-collapsed, with every numeric token a group."""
    collapsed = " ".join(line.split())
    parts, groups, at = [], [], 0
    for index, match in enumerate(numeric.finditer(collapsed), start=1):
        parts.append(re.escape(collapsed[at:match.start()]))
        parts.append(f"({re.escape(match.group())})")
        groups.append(index)
        at = match.end()
    parts.append(re.escape(collapsed[at:]))
    return "".join(parts), tuple(groups)


def document_pins(numeric: re.Pattern[str]) -> list[tuple[str, str, str, tuple[int, ...], object]]:
    """``(what, path, pattern, groups, expected)`` for every number section 12 of `DATASET_D1.md` states: one
    row per line of its two tables, every numeric token a group, and one per count and coefficient of the
    prose, ``expected`` computed from the comparison or the module. ``numeric`` is the prose check's
    tokenizer."""
    rows = comparison()
    c = lifetime.document_counts(rows)
    pins: list[tuple[str, str, str, tuple[int, ...], object]] = [
        ("measurements of the first source", DOCUMENT, r"the (\d+) rows of Tables III and IV", (1,),
         c["suzuki"]),
        ("measurements of the second source", DOCUMENT, r"the (\d+) rows of Table 1 of Mizuno", (1,),
         c["mizuno"]),
        ("measurements compared", DOCUMENT, r"Of the (\d+) measurements compared", (1,), c["measured"]),
        ("helper decay rates below", DOCUMENT, r"less the printed capture rate for (\d+),", (1,),
         c["helper_below"]),
        ("bound decay rates below", DOCUMENT, r"`G4MuonMinusBoundDecay` for (\d+)\.", (1,), c["bound_below"]),
        ("the helper's coefficient", DOCUMENT, r"unity and (\d+\.\d+) times the square", (1,),
         repr(lifetime.HELPER_SCALE)),
        ("the band's multiple", DOCUMENT, r"by no more than (\w+) times the root sum", (1,), "three"),
    ]
    for name, block in (("summary table", lifetime.render_summary_table(rows)),
                        ("outside table", lifetime.render_outside_table(rows))):
        for number, line in enumerate(block.splitlines()[2:], start=1):
            pattern, groups = _row_pattern(line, numeric)
            pins.append((f"{name} row {number}", DOCUMENT, pattern, groups, None))
    return pins


_NUMERIC = re.compile(r"[0-9][0-9,.]*[0-9]|[0-9]|[⁰¹²³⁴⁵⁶⁷⁸⁹]+")


def test_the_document_carries_both_tables_as_generated():
    """Section 12 of `DATASET_D1.md` carries each table exactly as the comparison renders it."""
    section = (REPO / DOCUMENT).read_text(encoding="utf-8").split("\n## 12. ", 1)[1]
