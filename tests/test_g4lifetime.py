"""The decay rate of a muon bound in a muonic atom on Geant4's two routes, and the comparison of each route's
disappearance rate with the mean lives the sources measured.

`data/g4/d1/d1_decay_rate.oracle` is what `cpp/tools/harvest_decay.cc` printed on Geant4 builds, and
`data/g4/d1/mean_life_comparison.csv` is generated by `scripts/generate_g4lifetime.py compare`. These tests
recompute every decay rate of the oracle, evaluated with the oracle's constants and nuclear-mass inputs, tie
the oracle to the driver and the ports to the vendored source, regenerate the comparison and compare its
bytes, drill each refusal and each class a row can take.
"""

