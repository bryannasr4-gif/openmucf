def test_the_helper_decay_rate_is_reproduced_bit_for_bit():
    """Every rate the oracle holds for `G4MuonicAtomHelper::GetMuonDecayRate(Z)`, the clamped edges and the
    one tabulated rate included, is the port's to the last bit."""
    found = helper()
    zmin, zmax = lifetime.helper_clamp(found)
    rates = oracle().helper
    assert sorted(rates) == list(lifetime.HELPER_Z)
    for z, rate in rates.items():
        assert lifetime.helper_decay_rate(z, found.zeff, zmin, zmax) == rate, z


def test_the_bound_decay_rate_is_reproduced_bit_for_bit_with_the_mass_below_the_threshold():
    """Below the threshold every rate the oracle holds is the port's, given the nuclear mass the build
    passed."""
    data = oracle()
    assert sorted(data.light) == lifetime.light_keys()
    for (z, a), (mass, rate) in data.light.items():
        assert lifetime.bound_decay_rate(z, a, data.constants["mu_mass"], mass) == rate, (z, a)


def test_the_bound_decay_rate_reads_no_mass_from_the_threshold_on():
    """From the threshold on, the port given no mass at all (NaN, which would spread to the rate if it were
    read) returns every rate of the oracle, and the digest over every A of the sweep, which the harvest
    checked the build returns the same rate for, is the port's."""
    data = oracle()
    mu_mass = data.constants["mu_mass"]
    assert sorted(data.heavy) == list(range(lifetime.BOUND_THRESHOLD_Z, lifetime.HIGH_Z_MAX + 1))
    for z, rate in data.heavy.items():
        assert lifetime.bound_decay_rate(z, z, mu_mass, math.nan) == rate, z
    rates = [lifetime.bound_decay_rate(z, a, mu_mass, math.nan) for z, a in lifetime.heavy_keys()]
    assert lifetime.digest(rates) == data.header["heavy_sha256"]


def test_drill_a_port_that_reads_the_mass_from_the_threshold_on_misses_the_digest(monkeypatch):
    """A port that reads the mass at the threshold's own Z, evaluated over the keys the digest is over (taken
    before the threshold moves, so the threshold's Z stays in them, with no mass), misses the digest."""
    keys = lifetime.heavy_keys()
    data = oracle()
    mu_mass = data.constants["mu_mass"]
    first = lifetime.BOUND_THRESHOLD_Z
    monkeypatch.setattr(lifetime, "BOUND_THRESHOLD_Z", first + 1)
    rates = [lifetime.bound_decay_rate(z, a, mu_mass, math.nan) for z, a in keys]
    reached = [rate for (z, _), rate in zip(keys, rates, strict=True) if z == first]
    assert reached and all(math.isnan(rate) for rate in reached)
    assert lifetime.digest(rates) != data.header["heavy_sha256"]


