@pytest.mark.parametrize("revision", REVISIONS)
def test_the_ports_transcribe_the_vendored_decay_functions(revision):
    """Both vendored revisions write the two decay functions as the ports transcribe them, and the literals
    the ports carry are the ones those functions write."""
    base = REPO / "third_party" / "geant4" / revision
    bound = (base / "G4MuonMinusBoundDecay.cc").read_text(encoding="ascii")
    assert function_body(bound, BOUND_SIGNATURE) == BOUND_BODY
    helper_text = (base / "G4MuonicAtomHelper.cc").read_text(encoding="ascii")
    assert function_body(helper_text, HELPER_SIGNATURE) == HELPER_BODY
    for literal in (lifetime.FREE_DECAY_RATE, lifetime.LIGHT_SCALE, lifetime.LIGHT_MASS_SCALE,
                    lifetime.HEAVY_SCALE, lifetime.HEAVY_SLOPE):
        assert repr(literal) in BOUND_BODY, literal
    assert f"if(Z<{lifetime.BOUND_THRESHOLD_Z})" in BOUND_BODY
    assert f"{{{{1,{lifetime.HELPER_HYDROGEN_RATE!r}," in HELPER_BODY
    assert f"lambda-={lifetime.HELPER_SCALE!r}*x*x" in HELPER_BODY


@pytest.mark.parametrize("revision", REVISIONS)
def test_the_patches_leave_both_decay_functions_as_they_are(revision):
    """The behaviour patch of each revision, applied to the vendored files, changes neither decay function;
    the helper's effective charge, which its decay rate reads, is the one function of the two files the
    dataset's `muon_zeff` table answers."""
    behaviour, _, _ = overlay.FAMILIES[revision]
    files = overlay.by_new_path(overlay.parse_patch(behaviour.read_bytes()))
    for path, vendored in overlay.SEAMS[revision].items():
        if vendored.name not in ("G4MuonMinusBoundDecay.cc", "G4MuonicAtomHelper.cc"):
            continue
        original = vendored.read_bytes()
        patched = overlay.apply_file_patch(files[path], original).decode("ascii")
        signature = BOUND_SIGNATURE if vendored.name == "G4MuonMinusBoundDecay.cc" else HELPER_SIGNATURE
        assert function_body(patched, signature) == function_body(original.decode("ascii"), signature), path
        if vendored.name == "G4MuonicAtomHelper.cc":
            zeff = function_body(patched, "G4double G4MuonicAtomHelper::GetMuonZeff(G4int Z)")
            assert "G4MuonicDataOverlay::Zeff(Z)" in zeff


def test_the_oracle_records_the_committed_driver_on_both_revisions():
    """The oracle names the committed driver by its SHA-256, both builds with the version each
    `geant4-config` printed (the beta's prints its release number without the suffix), and the flags the
    public recipe compiles the driver with."""
    header = oracle().header
    assert header["driver"] == lifetime.HARNESS_RELPATH
    driver = (REPO / lifetime.HARNESS_RELPATH).read_bytes()
    assert header["driver_sha256"] == hashlib.sha256(driver).hexdigest()
    expected = ", ".join(f"{build} ({revision.removeprefix('v').removesuffix('.beta')})"
                         for build, revision in lifetime.BUILDS)
    assert header["builds"].startswith(expected + ",")
    assert header["driver_flags"].startswith(" ".join(decay_harvest().FLAGS) + ";")


