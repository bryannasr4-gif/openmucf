def test_the_comparison_takes_each_sources_own_measurements_under_every_profile():
    """Every row is a measurement a source printed for its own measurement, under one profile of the
    capture table, and every profile carries every measurement once."""
    rows = comparison()
    profiles = list(natural.capture_profiles(REPO / "data" / "g4" / "d1"))
    measurements = [(row["source"], row["locator"]) for row in rows if row["profile"] == profiles[0]]
    assert len(measurements) == len(set(measurements))
    for name in profiles:
        assert [(row["source"], row["locator"]) for row in rows if row["profile"] == name] == measurements
    quantity = REPO / "data" / "g4" / "d1" / "suzuki1987_quantity_rows.csv"
    with quantity.open(encoding="utf-8", newline="") as handle:
        own = {f"Table {r['table']} p.{r['printed_page']} row {r['page_row_ordinal']}": r
               for r in csv.DictReader(handle)}
    for source, locator in measurements:
        if source == lifetime.SUZUKI:
            assert own[locator]["own_measurement"] == "true" and own[locator]["rate"], locator


def test_every_class_a_row_can_take_occurs_and_follows_from_the_row():
    """The classes are recomputed from each row's own columns: the source of the value that answers it, its
    lookup and the kind of target; every class occurs."""
    rows = comparison()
    isotopes = natural.load_isotopes(REPO / natural.ISOTOPES_RELPATH)
    references = natural.natural_references(d1.load_isotope_audit(REPO / d1.AUDIT_RELPATH))
    for row in rows:
        if not row["key_a"]:
            assert row["population"] == lifetime.NO_KEY
            continue
        z, a = int(row["z"]), int(row["key_a"])
        if row["lookup"] == lifetime.FORMULA_ROUTE:
            expected = lifetime.FORMULA
        else:
            source = row["profile"] if row["lookup"] == lifetime.PROFILE_ROUTE else lifetime.TABLE_SOURCE
            natural_record = row["lookup"] == lifetime.TABLE_ROUTE and references.get(z) == a
            basis = "natural" if natural_record else "isotope"
            measured = "isotope" if row["basis"] == "isotope" else "natural"
            if source != row["source"]:
                expected = lifetime.OTHER_SOURCE
            elif measured != basis and len(isotopes[z]) != 1:
                expected = lifetime.OTHER_BASIS
            else:
                expected = lifetime.COMPARED
        assert row["population"] == expected, (row["profile"], row["source"], row["locator"])
    assert {row["population"] for row in rows} == set(lifetime.POPULATIONS)


def test_every_route_rate_is_capture_plus_decay_and_every_band_decision_is_exact():
    """A compared row's route rates are the capture rate plus each decay rate, the helper's through the
    lifetime it gives the muonic atom; the band decision of every row with a capture uncertainty is the one
    an exact decimal recomputation from its printed values gives."""
    for row in comparison():
        if not row["capture_rate_unc"]:
            assert row["within_bound"] == row["within_helper"] == ""
            continue
        capture = float(row["capture_rate"])
        for suffix, _ in lifetime.ROUTES:
            total = capture + float(row[f"decay_rate_{suffix}"])
            assert math.isclose(float(row[f"rate_{suffix}"]), total, rel_tol=1e-14), (row["locator"], suffix)
            d = decimal.Decimal(row[f"rate_{suffix}"]) - decimal.Decimal(row["measured_rate"])
            s2 = sum(decimal.Decimal(row[name]) ** 2 for name in ("measured_rate_unc", "capture_rate_unc"))
            with decimal.localcontext() as context:
                context.prec = 400
                inside = d * d <= lifetime.K * lifetime.K * s2
            assert row[f"within_{suffix}"] == ("true" if inside else "false"), (row["locator"], suffix)


def test_drill_the_band_holds_its_edge_and_refuses_beyond_it():
    assert lifetime.within("1.3", "1.0", ("0.1", "0"))
    assert not lifetime.within("1.3000000000000001", "1.0", ("0.1", "0"))
    assert lifetime.within("0.7", "1.0", ("0.06", "0.08"))
    assert not lifetime.within("0.69", "1.0", ("0.06", "0.08"))


def test_drill_the_comparison_refuses_an_unknown_profile_a_differing_charge_and_a_differing_copy(monkeypatch):
    """The comparison is computed only when every profile's rows have a known source, when the `muon_zeff`
    table equals the helper's compiled effective charge at every Z it compares, and when the two compiled
    copies return the same capture rate."""
    tables = natural.capture_profiles(REPO / "data" / "g4" / "d1")
    with monkeypatch.context() as patch:
        planted = {**tables, "unknown": tables[lifetime.SUZUKI]}
        patch.setattr(natural, "capture_profiles", lambda directory: planted)
        with pytest.raises(lifetime.LifetimeError):
            lifetime.comparison_rows(REPO)
    found = helper()
    with monkeypatch.context() as patch:
        moved = replace(found, zeff=tuple(value * 1.5 for value in found.zeff))
        patch.setattr(d1, "load_helper", lambda path: moved)
        with pytest.raises(lifetime.LifetimeError):
            lifetime.comparison_rows(REPO)
    with monkeypatch.context() as patch:
        records = tuple((z, a, value * 2.0, unc) for z, a, value, unc in found.capture_records)
        patch.setattr(d1, "load_helper", lambda path: replace(found, capture_records=records))
        with pytest.raises(lifetime.LifetimeError):
            lifetime.comparison_rows(REPO)


def test_the_two_routes_are_the_ones_the_physics_lists_bind():
    """The reference lists QBBC and FTFP_BERT give the negative muon `G4MuonMinusCapture` at rest, and the
    configuration the D2 harness builds as `QBBC+helper` gives it `G4MuonMinusAtomicCapture`, registering
    `G4MuonicAtomDecayPhysics`; the BoundDecay route passes the stop's nucleus to the first decay rate and the
    helper's lifetime is one over capture plus the second."""
    with (REPO / "data" / "g4" / "d2" / "selector_bindings.csv").open(encoding="utf-8", newline="") as handle:
        bindings = [row for row in csv.DictReader(handle)
                    if row["particle"] == "mu-" and row["process"] != "Decay"]
    by_list = {(row["build"], row["physics_list"]): row["class"] for row in bindings}
    for (_, physics_list), process in by_list.items():
        expected = "G4MuonMinusAtomicCapture" if physics_list == "QBBC+helper" else "G4MuonMinusCapture"
        assert process == expected, physics_list
    assert {physics_list for _, physics_list in by_list} == {"QBBC", "FTFP_BERT", "QBBC+helper"}
    harness = (REPO / "cpp" / "tools" / "harvest_d2.cc").read_text(encoding="utf-8")
    assert "AddRestProcess(new G4MuonMinusAtomicCapture())" in harness
    assert "RegisterPhysics(new G4MuonicAtomDecayPhysics())" in harness
    for revision in REVISIONS:
        base = REPO / "third_party" / "geant4" / revision
        bound = re.sub(r"\s+", "", (base / "G4MuonMinusBoundDecay.cc").read_text(encoding="ascii"))
        call = "GetMuonDecayRate(Z,A,fMuMass,targetNucleus.AtomicMass(A,Z));G4doublelambda=lambdac+lambdad;"
        assert call in bound
        assert "G4doubletime=p->GetGlobalTime()-G4Log(G4UniformRand())/lambda;" in bound
        text = re.sub(r"\s+", "", (base / "G4MuonicAtomHelper.cc").read_text(encoding="ascii"))
        assert "G4doublelambdad=GetMuonDecayRate(Z);G4doublelifetime=1./(lambdac+lambdad);" in text
        decay = re.sub(r"\s+", "", (base / "G4MuonicAtomDecay.cc").read_text(encoding="ascii"))
        assert "G4doublemeanlife=muatom->GetPDGLifeTime();" in decay
