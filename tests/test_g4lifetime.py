def _rewritten(source: Path, target: Path, change) -> Path:
    with source.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        fields, rows = list(reader.fieldnames or ()), list(reader)
    change(rows)
    with target.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields, lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    return target


def _own(row: dict[str, str]) -> bool:
    printed = row["mean_life_ns"] and row["mean_life_unc_ns"] and row["rate"]
    return bool(row["own_measurement"] == "true" and printed)


def _foreign_basis(rows: list[dict[str, str]]) -> None:
    other = next(row["target_basis"] for row in rows
                 if row["target_basis"] not in ("isotope", "natural", "unspecified"))
    next(row for row in rows if _own(row))["target_basis"] = other


def _no_mass_number(rows: list[dict[str, str]]) -> None:
    row = next(row for row in rows if _own(row) and row["target_basis"] == "isotope")
    row["target_label"] = re.sub(r"^[0-9]+", "", row["target_label"])


